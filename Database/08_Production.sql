/* ---------------------------------------------------------------------
   Weekly production & environment (called after sp_FlockWeekly_Save, same transaction)
   Hen-day production % = total eggs x 100 / female bird-days of the week
   --------------------------------------------------------------------- */
CREATE OR ALTER PROCEDURE dbo.sp_FlockWeekly_SaveProduction
    @FlockWeeklyID INT,
    @TotalEggs INT = NULL, @HatchingEggs INT = NULL, @FloorEggs INT = NULL, @DirtyEggs INT = NULL,
    @BrokenEggs INT = NULL, @CrackedEggs INT = NULL, @DoubleYolkEggs INT = NULL, @AvgEggWeight DECIMAL(8,2) = NULL,
    @LightHours DECIMAL(5,2) = NULL, @LightIntensity DECIMAL(8,2) = NULL, @TempDay DECIMAL(5,2) = NULL, @TempNight DECIMAL(5,2) = NULL,
    @UserID INT, @UserName NVARCHAR(50), @IPAddress NVARCHAR(50) = NULL, @Recalculate BIT = 1
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @FlockID INT, @WeekNo INT, @HenDays DECIMAL(18,4), @Housed INT;
    SELECT @FlockID = w.FlockID, @WeekNo = w.WeekNo,
           @HenDays = (w.ClosingFemale + w.FemaleMortality + w.FemaleCulling + w.TransferOutFemale - w.ReceivedFemale + w.ClosingFemale) / 2.0 * 7,
           @Housed = f.FemaleCount
    FROM dbo.tblFlockWeekly w INNER JOIN dbo.tblFlock f ON f.FlockID = w.FlockID
    WHERE w.FlockWeeklyID = @FlockWeeklyID;
    IF @FlockID IS NULL THROW 50400, N'Weekly entry not found.', 1;

    IF @TotalEggs < 0 OR @HatchingEggs < 0 OR @FloorEggs < 0 OR @DirtyEggs < 0 OR @BrokenEggs < 0 OR @CrackedEggs < 0 OR @DoubleYolkEggs < 0
        THROW 50401, N'Egg counts cannot be negative.', 1;
    IF @HatchingEggs > ISNULL(@TotalEggs, 0)
        THROW 50402, N'Hatching eggs cannot exceed the total eggs collected.', 1;
    IF @TotalEggs > 0 AND @HenDays > 0 AND @TotalEggs > @HenDays * 1.05
        THROW 50403, N'Total eggs are more than one egg per hen per day. Check the egg count.', 1;
    IF @AvgEggWeight IS NOT NULL AND (@AvgEggWeight < 20 OR @AvgEggWeight > 120)
        THROW 50404, N'Average egg weight must be between 20 and 120 g.', 1;
    IF @LightHours IS NOT NULL AND (@LightHours < 0 OR @LightHours > 24)
        THROW 50405, N'Light hours must be between 0 and 24.', 1;
    IF @LightIntensity < 0
        THROW 50406, N'Light intensity cannot be negative.', 1;
    IF (@TempDay IS NOT NULL AND (@TempDay < -20 OR @TempDay > 60)) OR (@TempNight IS NOT NULL AND (@TempNight < -20 OR @TempNight > 60))
        THROW 50407, N'Temperatures must be between -20 and 60 degrees C.', 1;

    DECLARE @Old NVARCHAR(MAX) = (
        SELECT w.LightHours, w.LightIntensity, w.TempDay, w.TempNight, e.TotalEggs, e.HatchingEggs, e.AvgEggWeight
        FROM dbo.tblFlockWeekly w LEFT JOIN dbo.tblEggProductionWeekly e ON e.FlockWeeklyID = w.FlockWeeklyID
        WHERE w.FlockWeeklyID = @FlockWeeklyID FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);

    BEGIN TRANSACTION;

    UPDATE dbo.tblFlockWeekly
       SET LightHours = @LightHours, LightIntensity = @LightIntensity, TempDay = @TempDay, TempNight = @TempNight
     WHERE FlockWeeklyID = @FlockWeeklyID;

    IF @TotalEggs IS NULL AND @HatchingEggs IS NULL AND @AvgEggWeight IS NULL
        DELETE FROM dbo.tblEggProductionWeekly WHERE FlockWeeklyID = @FlockWeeklyID;
    ELSE
    BEGIN
        DECLARE @HD DECIMAL(9,4) = CASE WHEN @HenDays > 0 THEN ISNULL(@TotalEggs, 0) * 100.0 / @HenDays END;
        DECLARE @Cum DECIMAL(12,4) = CASE WHEN @Housed > 0 THEN
            (ISNULL((SELECT SUM(e.TotalEggs) FROM dbo.tblEggProductionWeekly e INNER JOIN dbo.tblFlockWeekly x ON x.FlockWeeklyID = e.FlockWeeklyID
                     WHERE x.FlockID = @FlockID AND x.WeekNo < @WeekNo), 0) + ISNULL(@TotalEggs, 0)) * 1.0 / @Housed END;

        MERGE dbo.tblEggProductionWeekly AS t
        USING (SELECT @FlockWeeklyID AS FlockWeeklyID) AS s ON t.FlockWeeklyID = s.FlockWeeklyID
        WHEN MATCHED THEN UPDATE SET HenHousedCount = ISNULL(@Housed, 0), TotalEggs = ISNULL(@TotalEggs, 0),
             HatchingEggs = ISNULL(@HatchingEggs, 0), FloorEggs = ISNULL(@FloorEggs, 0), DirtyEggs = ISNULL(@DirtyEggs, 0),
             BrokenEggs = ISNULL(@BrokenEggs, 0), CrackedEggs = ISNULL(@CrackedEggs, 0), DoubleYolkEggs = ISNULL(@DoubleYolkEggs, 0),
             AvgEggWeight = @AvgEggWeight, HenDayProductionPct = @HD, HenHousedEggsCum = @Cum
        WHEN NOT MATCHED THEN INSERT (FlockWeeklyID, HenHousedCount, TotalEggs, HatchingEggs, FloorEggs, DirtyEggs, BrokenEggs,
                                      CrackedEggs, DoubleYolkEggs, AvgEggWeight, HenDayProductionPct, HenHousedEggsCum)
             VALUES (@FlockWeeklyID, ISNULL(@Housed, 0), ISNULL(@TotalEggs, 0), ISNULL(@HatchingEggs, 0), ISNULL(@FloorEggs, 0),
                     ISNULL(@DirtyEggs, 0), ISNULL(@BrokenEggs, 0), ISNULL(@CrackedEggs, 0), ISNULL(@DoubleYolkEggs, 0),
                     @AvgEggWeight, @HD, @Cum);
    END

    IF @Recalculate = 1
        EXEC dbo.sp_CalculateFlockPerformance @FlockWeeklyID = @FlockWeeklyID;

    DECLARE @New NVARCHAR(MAX) = (
        SELECT w.LightHours, w.LightIntensity, w.TempDay, w.TempNight, e.TotalEggs, e.HatchingEggs, e.AvgEggWeight, e.HenDayProductionPct
        FROM dbo.tblFlockWeekly w LEFT JOIN dbo.tblEggProductionWeekly e ON e.FlockWeeklyID = w.FlockWeeklyID
        WHERE w.FlockWeeklyID = @FlockWeeklyID FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    IF ISNULL(@Old, N'') <> ISNULL(@New, N'')
        EXEC dbo.sp_AuditLog_Insert @UserID, @UserName, N'UPDATE', N'tblEggProductionWeekly', @FlockWeeklyID, @Old, @New, @IPAddress;

    COMMIT TRANSACTION;
END
GO

/* ---------------------------------------------------------------------
   HATCH RESULTS (one row per setting of eggs from one flock-week)
   --------------------------------------------------------------------- */
CREATE OR ALTER PROCEDURE dbo.sp_HatchResult_Search
    @FarmID INT = NULL, @FlockID INT = NULL, @FromDate DATE = NULL, @ToDate DATE = NULL,
    @RestrictFarmID INT = NULL, @PageNumber INT = 1, @PageSize INT = 25
AS
BEGIN
    SET NOCOUNT ON;
    SELECT  hr.HatchResultID, hr.FlockID, f.FlockNumber, fm.FarmName, h.HouseName, bt.BirdTypeName, hr.WeekNo,
            hr.SetDate, hr.HatchDate, hr.SettableEggs, hr.InfertileEggs, hr.FertileEggs, hr.DeadInShell, hr.HatchedChicks,
            hr.SaleableChicks, hr.FertilityPct, CASE WHEN hr.HatchDate IS NOT NULL THEN hr.HatchabilityPct END AS HatchabilityPct,
            CASE WHEN hr.HatchDate IS NOT NULL THEN hr.HatchOfFertilePct END AS HatchOfFertilePct,
            hr.Remarks, u.FullName AS CreatedByName, hr.CreatedDate,
            COUNT(*) OVER () AS TotalRows
    FROM    dbo.tblHatchResult hr
    INNER JOIN dbo.tblFlock f ON f.FlockID = hr.FlockID
    INNER JOIN dbo.tblFarm fm ON fm.FarmID = f.FarmID
    INNER JOIN dbo.tblHouse h ON h.HouseID = f.HouseID
    INNER JOIN dbo.tblBirdType bt ON bt.BirdTypeID = f.BirdTypeID
    LEFT  JOIN dbo.tblUsers u ON u.UserID = hr.CreatedBy
    WHERE   (@FarmID IS NULL OR f.FarmID = @FarmID)
      AND   (@FlockID IS NULL OR hr.FlockID = @FlockID)
      AND   (@FromDate IS NULL OR hr.SetDate >= @FromDate)
      AND   (@ToDate IS NULL OR hr.SetDate <= @ToDate)
      AND   (@RestrictFarmID IS NULL OR f.FarmID = @RestrictFarmID)
    ORDER BY hr.SetDate DESC, hr.HatchResultID DESC
    OFFSET (@PageNumber - 1) * @PageSize ROWS FETCH NEXT @PageSize ROWS ONLY;
END
GO

CREATE OR ALTER PROCEDURE dbo.sp_HatchResult_Save
    @HatchResultID INT, @FlockID INT, @WeekNo INT, @SetDate DATE, @HatchDate DATE = NULL,
    @SettableEggs INT, @InfertileEggs INT = 0, @DeadInShell INT = 0, @HatchedChicks INT = 0, @SaleableChicks INT = NULL,
    @Remarks NVARCHAR(250) = NULL,
    @UserID INT, @UserName NVARCHAR(50), @IPAddress NVARCHAR(50) = NULL,
    @NewHatchResultID INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @msg NVARCHAR(400), @Hatch DATE, @OldFlock INT, @OldWeek INT;
    SELECT @Hatch = HatchDate FROM dbo.tblFlock WHERE FlockID = @FlockID;
    IF @Hatch IS NULL THROW 50410, N'Flock not found.', 1;
    IF @HatchResultID > 0
    BEGIN
        SELECT @OldFlock = FlockID, @OldWeek = WeekNo FROM dbo.tblHatchResult WHERE HatchResultID = @HatchResultID;
        IF @OldFlock IS NULL THROW 50411, N'Hatch result not found.', 1;
    END
    IF NOT EXISTS (SELECT 1 FROM dbo.tblFlockWeekly WHERE FlockID = @FlockID AND WeekNo = @WeekNo)
    BEGIN
        SET @msg = CONCAT(N'Week ', @WeekNo, N' has not been entered for this flock. Choose the week the eggs were laid in.');
        THROW 50412, @msg, 1;
    END
    IF @SetDate IS NULL OR @SetDate < DATEADD(DAY, 7 * (@WeekNo - 1) + 1, @Hatch) OR @SetDate > CONVERT(DATE, GETDATE())
        THROW 50413, N'Set date must be after the start of the egg week and not in the future.', 1;
    IF @HatchDate IS NOT NULL AND (@HatchDate < DATEADD(DAY, 18, @SetDate) OR @HatchDate > CONVERT(DATE, GETDATE()))
        THROW 50414, N'Hatch date must be at least 18 days after the set date and not in the future.', 1;
    IF @SettableEggs <= 0 OR @InfertileEggs < 0 OR @DeadInShell < 0 OR @HatchedChicks < 0 OR @SaleableChicks < 0
        THROW 50415, N'Egg and chick counts must be positive.', 1;
    IF @InfertileEggs > @SettableEggs
        THROW 50416, N'Infertile eggs cannot exceed the eggs set.', 1;
    IF @HatchedChicks + @DeadInShell > @SettableEggs - @InfertileEggs
        THROW 50417, N'Chicks hatched plus dead-in-shell cannot exceed the fertile eggs.', 1;
    IF @HatchDate IS NULL AND (@HatchedChicks > 0 OR @SaleableChicks > 0)
        THROW 50418, N'Enter the hatch date together with the chicks hatched.', 1;
    IF @SaleableChicks > @HatchedChicks
        THROW 50419, N'Saleable chicks cannot exceed the chicks hatched.', 1;

    DECLARE @Old NVARCHAR(MAX), @New NVARCHAR(MAX), @id INT;
    BEGIN TRANSACTION;
    IF @HatchResultID = 0
    BEGIN
        INSERT INTO dbo.tblHatchResult (FlockID, WeekNo, SetDate, HatchDate, SettableEggs, InfertileEggs, DeadInShell,
                                        HatchedChicks, SaleableChicks, Remarks, CreatedBy)
        VALUES (@FlockID, @WeekNo, @SetDate, @HatchDate, @SettableEggs, @InfertileEggs, @DeadInShell, @HatchedChicks,
                @SaleableChicks, @Remarks, @UserID);
        SET @id = SCOPE_IDENTITY();
    END
    ELSE
    BEGIN
        SET @id = @HatchResultID;
        SET @Old = (SELECT FlockID, WeekNo, SetDate, HatchDate, SettableEggs, InfertileEggs, DeadInShell, HatchedChicks, SaleableChicks, Remarks
                    FROM dbo.tblHatchResult WHERE HatchResultID = @id FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
        UPDATE dbo.tblHatchResult
           SET FlockID = @FlockID, WeekNo = @WeekNo, SetDate = @SetDate, HatchDate = @HatchDate, SettableEggs = @SettableEggs,
               InfertileEggs = @InfertileEggs, DeadInShell = @DeadInShell, HatchedChicks = @HatchedChicks,
               SaleableChicks = @SaleableChicks, Remarks = @Remarks, ModifiedBy = @UserID, ModifiedDate = SYSDATETIME()
         WHERE HatchResultID = @id;
    END
    SET @New = (SELECT FlockID, WeekNo, SetDate, HatchDate, SettableEggs, InfertileEggs, DeadInShell, HatchedChicks, SaleableChicks, Remarks
                FROM dbo.tblHatchResult WHERE HatchResultID = @id FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    DECLARE @Action NVARCHAR(20) = CASE WHEN @Old IS NULL THEN N'INSERT' ELSE N'UPDATE' END;
    EXEC dbo.sp_AuditLog_Insert @UserID, @UserName, @Action, N'tblHatchResult', @id, @Old, @New, @IPAddress;

    /* refresh fertility / hatchability status and alerts of the egg week (and the old one if it moved) */
    DECLARE @w INT = (SELECT FlockWeeklyID FROM dbo.tblFlockWeekly WHERE FlockID = @FlockID AND WeekNo = @WeekNo);
    IF @w IS NOT NULL EXEC dbo.sp_CalculateFlockPerformance @FlockWeeklyID = @w;
    IF @OldFlock IS NOT NULL AND (@OldFlock <> @FlockID OR @OldWeek <> @WeekNo)
    BEGIN
        SET @w = (SELECT FlockWeeklyID FROM dbo.tblFlockWeekly WHERE FlockID = @OldFlock AND WeekNo = @OldWeek);
        IF @w IS NOT NULL EXEC dbo.sp_CalculateFlockPerformance @FlockWeeklyID = @w;
    END
    COMMIT TRANSACTION;
    SET @NewHatchResultID = @id;
END
GO

CREATE OR ALTER PROCEDURE dbo.sp_HatchResult_Delete
    @HatchResultID INT, @UserID INT, @UserName NVARCHAR(50), @IPAddress NVARCHAR(50) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    DECLARE @FlockID INT, @WeekNo INT, @Old NVARCHAR(MAX);
    SELECT @FlockID = FlockID, @WeekNo = WeekNo FROM dbo.tblHatchResult WHERE HatchResultID = @HatchResultID;
    IF @FlockID IS NULL THROW 50411, N'Hatch result not found.', 1;
    SET @Old = (SELECT * FROM dbo.tblHatchResult WHERE HatchResultID = @HatchResultID FOR JSON PATH, WITHOUT_ARRAY_WRAPPER);
    BEGIN TRANSACTION;
    DELETE FROM dbo.tblHatchResult WHERE HatchResultID = @HatchResultID;
    EXEC dbo.sp_AuditLog_Insert @UserID, @UserName, N'DELETE', N'tblHatchResult', @HatchResultID, @Old, NULL, @IPAddress;
    DECLARE @w INT = (SELECT FlockWeeklyID FROM dbo.tblFlockWeekly WHERE FlockID = @FlockID AND WeekNo = @WeekNo);
    IF @w IS NOT NULL EXEC dbo.sp_CalculateFlockPerformance @FlockWeeklyID = @w;
    COMMIT TRANSACTION;
END
GO

/* production & environment block of one week + its hatch results (weekly entry tab, analysis screen) */
CREATE OR ALTER PROCEDURE dbo.sp_FlockWeekly_GetProduction
    @FlockWeeklyID INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT  w.FlockWeeklyID, w.LightHours, w.LightIntensity, w.TempDay, w.TempNight,
            e.TotalEggs, e.HatchingEggs, e.FloorEggs, e.DirtyEggs, e.BrokenEggs, e.CrackedEggs, e.DoubleYolkEggs,
            e.AvgEggWeight, e.HenDayProductionPct, e.HenHousedEggsCum, e.HenHousedCount,
            CAST((w.ClosingFemale + w.FemaleMortality + w.FemaleCulling + w.TransferOutFemale - w.ReceivedFemale + w.ClosingFemale) / 2.0 * 7
                 AS DECIMAL(18,1)) AS HenDays
    FROM    dbo.tblFlockWeekly w
    LEFT JOIN dbo.tblEggProductionWeekly e ON e.FlockWeeklyID = w.FlockWeeklyID
    WHERE   w.FlockWeeklyID = @FlockWeeklyID;

    SELECT  hr.HatchResultID, hr.SetDate, hr.HatchDate, hr.SettableEggs, hr.InfertileEggs, hr.FertileEggs, hr.DeadInShell,
            hr.HatchedChicks, hr.SaleableChicks, hr.FertilityPct,
            CASE WHEN hr.HatchDate IS NOT NULL THEN hr.HatchabilityPct END AS HatchabilityPct,
            CASE WHEN hr.HatchDate IS NOT NULL THEN hr.HatchOfFertilePct END AS HatchOfFertilePct
    FROM    dbo.tblHatchResult hr
    INNER JOIN dbo.tblFlockWeekly w ON w.FlockID = hr.FlockID AND w.WeekNo = hr.WeekNo
    WHERE   w.FlockWeeklyID = @FlockWeeklyID
    ORDER BY hr.SetDate;
END
GO

